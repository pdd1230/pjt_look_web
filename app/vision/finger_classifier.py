# MediaPipe 랜드마크 번호
WRIST = 0
THUMB_IP, THUMB_TIP = 3, 4
INDEX_MCP = 5
MIDDLE_MCP = 9
PINKY_MCP = 17
# 손가락 이름: (뿌리 MCP, 두 번째 관절 PIP, 세 번째 관절 DIP, 손끝 TIP) 번호
FINGERS = {
    "index": (5, 6, 7, 8),
    "middle": (9, 10, 11, 12),
    "ring": (13, 14, 15, 16),
    "pinky": (17, 18, 19, 20),
}


def _dist(a, b):
    """두 점 (x, y, z) 사이의 2D 거리."""
    return math.hypot(a[0] - b[0], a[1] - b[1])


def _side(a, b, p):
    """직선 a->b 의 어느 쪽에 점 p 가 있는지. 부호가 같으면 같은 쪽, 다르면 반대쪽 (외적)."""
    return (b[0] - a[0]) * (p[1] - a[1]) - (b[1] - a[1]) * (p[0] - a[0])


def _palm_size(hand):
    """손바닥 크기(2D). 보통은 손목~중지 뿌리 길이.
    손끝이 카메라를 향하면 이 길이가 원근 때문에 짧아져(주먹을 카메라 쪽으로 내밀 때 등) 모든 거리비가 부풀려진다.
    그래서 손바닥 너비(검지 뿌리~새끼 뿌리, 길이의 약 0.85배)로 환산한 값과 비교해 큰 쪽을 쓴다.
    (옆모습은 너비가 줄어들 뿐 길이는 그대로라 영향이 없다.)
    """
    length = _dist(hand[WRIST], hand[MIDDLE_MCP])
    width = _dist(hand[INDEX_MCP], hand[PINKY_MCP]) / PALM_WIDTH_RATIO
    return max(length, width, 1e-6)

def _touches_thumb(hand, finger_tip):
    """그 손끝이 엄지 끝에 닿아 있으면 True (손바닥 크기 x THUMB_TOUCH_RATIO 보다 가까움)."""
    palm_size = _dist(hand[WRIST], hand[MIDDLE_MCP])   # 손목 ~ 중지 뿌리 = 손바닥 크기
    return _dist(hand[THUMB_TIP], hand[finger_tip]) < palm_size * THUMB_TOUCH_RATIO


def _finger_hidden(hand, depth, mcp, pip, dip, tip):
    """검지~새끼의 손끝이 다른 관절 뒤에 가려져 있으면 True.

    MediaPipe 는 가려진 관절도 21개를 항상 찍는다. 화면 거리로 겹침을 보고, 어느 쪽이 가려졌는지는
    z(작을수록 카메라에 가까움)로 가른다. 엄지보다 깊이 차이를 크게 봐서, 살짝 겹친 손가락은 펴짐으로 둔다.
    끝(TIP)만 본다. 뿌리 쪽은 옆 손가락과 원래 가까워서, 곧게 편 손가락까지 접힘으로 나왔다.
    """
    if depth is None:
        return False
    own = {mcp, pip, dip, tip}
    palm = _palm_size(hand)
    palm_z = _dist(hand[WRIST], hand[MIDDLE_MCP]) or 1e-6
    for j in range(21):
        if j in own:
            continue
        near = _dist(hand[tip], hand[j]) < FINGER_HIDE_RADIUS * palm
        closer = depth[j] < depth[tip] - FINGER_HIDE_DEPTH * palm_z
        if near and closer:
            return True
    return False


def _thumb_hidden(hand, depth):
    """엄지 끝이 다른 손가락 관절 뒤에 가려져 있으면 True. 가려진 엄지는 모델이 엉뚱한 곳에 점을 찍으므로 펴졌다고 믿을 수 없다.

    판단은 화면의 관절 번호 숨김(visualizer)과 같다: 화면에서 가까이(THUMB_HIDE_RADIUS) 겹쳐 있고
    그쪽 관절이 카메라에 더 가까우면(z 가 작으면) 가려진 것으로 본다. depth: 관절별 z (화면 x 와 같은 단위).
    """
    if depth is None:
        return False
    palm = _palm_size(hand)
    palm_z = _dist(hand[WRIST], hand[MIDDLE_MCP]) or 1e-6
    for j in range(5, 21):
        near = _dist(hand[THUMB_TIP], hand[j]) < THUMB_HIDE_RADIUS * palm
        closer = depth[j] < depth[THUMB_TIP] - THUMB_HIDE_DEPTH * palm_z
        if near and closer:
            return True
    return False


def diagnose_thumb(hand, world=None, depth=None, fist=True):
    """엄지를 판정하고 '왜 그렇게 나왔는지'도 같이 돌려준다. 반환: (펴짐 여부, 이유, 측정값 dict).

    이유: 3D-spread(3D 로 손에 붙음) / spread(검지 뿌리에 붙음) / center(손바닥 위에 있음) /
          bent(엄지 마디가 꺾임) / near(손에서 멀어지지 않음) / open(펴짐)
    측정값: spread2d(엄지끝~검지뿌리 / 손바닥), center2d(엄지끝~손바닥 중심 / 손바닥), ip2d(엄지 IP 각도),
            spread3d(3D 엄지끝~검지뿌리 / 손바닥)
    """
    palm_size = _palm_size(hand)
    ids = (WRIST, INDEX_MCP, MIDDLE_MCP, 13, PINKY_MCP)
    center_x = sum(hand[i][0] for i in ids) / 5
    center_y = sum(hand[i][1] for i in ids) / 5
    near_center = math.hypot(hand[THUMB_TIP][0] - center_x, hand[THUMB_TIP][1] - center_y) / palm_size
    spread_from_index = _dist(hand[THUMB_TIP], hand[INDEX_MCP]) / palm_size
    thumb_angle = _angle(hand[2], hand[THUMB_IP], hand[THUMB_TIP])   # 엄지 MCP-IP-TIP 각도
    metrics = {"spread2d": spread_from_index, "center2d": near_center, "ip2d": thumb_angle}

    if _thumb_hidden(hand, depth):
        return False, "hidden", metrics   # 엄지 끝이 다른 손가락 뒤에 가려져 있다 -> 보이지 않는 엄지는 접힌 것으로 본다

    # 화면에서 엄지가 손바닥 바깥(엄지 쪽 가장자리 밖, 손목~검지 뿌리 직선을 기준으로 중지 뿌리의 반대쪽)에 길고 곧게 뻗어 있으면
    # '눈에 보이는 편 엄지'다. 접어서 손바닥 위에 올린 엄지는 손바닥 안쪽(중지 뿌리 쪽)에 있다.
    metrics["reach2d"] = _dist(hand[1], hand[THUMB_TIP]) / palm_size   # 엄지 뿌리~끝 / 손바닥
    side_tip = _side(hand[WRIST], hand[INDEX_MCP], hand[THUMB_TIP])
    side_mid = _side(hand[WRIST], hand[INDEX_MCP], hand[MIDDLE_MCP])
    outside_palm = side_tip * side_mid < 0
    metrics["outside"] = 1.0 if outside_palm else 0.0
    visible_thumb = outside_palm and metrics["reach2d"] >= THUMB_REACH_MIN_SIDE and thumb_angle >= THUMB_STRAIGHT_ANGLE_SIDE

    if world is not None:
        palm3d = math.dist(world[WRIST], world[MIDDLE_MCP]) or 1e-6
        metrics["spread3d"] = math.dist(world[THUMB_TIP], world[INDEX_MCP]) / palm3d
        # 엄지가 손 뒤에 가려지면 모델이 관절을 엉뚱한 곳에 찍는다. 화면(2D)에서는 펴진 엄지처럼 보여도 3D 로는 손에 붙어 있다.
        # 단, 화면에서 엄지가 손바닥 중심에서 확실히 멀리(WORLD_THUMB_CENTER_MAX) 떨어져 있으면 3D 값은 믿지 않는다.
        # (옆모습 엄지척은 3D 값이 틀어지기 쉽지만 화면에서는 엄지가 손 위로 길게 뻗어 있다.)
        # 손바닥 바깥에 눈에 보이는 편 엄지(visible_thumb)도 믿지 않는다: 손을 기울이면 3D 엄지 거리가 0.2~0.3 으로 틀어졌다.
        # 다만 그 예외는 화면 각도가 160도 이상인 곧은 엄지에만 둔다. 각도가 그보다 작은데 3D 로 검지에 붙어 있으면
        # 손목을 기울여 화면에서 멀리 보여도 접힌 엄지다. (101219: 각도 151, 중심 1.22, 3D 거리 0.36)
        # (가려진 엄지는 위 _thumb_hidden 이 z 로 따로 거른다.)
        stuck_in_3d = metrics["spread3d"] < WORLD_THUMB_SPREAD_MIN
        if stuck_in_3d and thumb_angle < THUMB_STRAIGHT_ANGLE:
            return False, "3D-spread", metrics
        if stuck_in_3d and near_center < WORLD_THUMB_CENTER_MAX and not visible_thumb:
            return False, "3D-spread", metrics

    # 엄지가 손바닥 안쪽으로 접혔는지는 '새끼 뿌리'와 '검지 뿌리' 두 곳에서 모두 잰다.
    # 새끼 뿌리 하나만 쓰면 OK 사인처럼 엄지를 옆으로 뻗은 자세에서 거리비가 1.0 근처로 떨어져
    # 펴진 엄지가 굽힘으로 나왔다. 둘 중 한쪽이라도 엄지 끝이 관절보다 멀면 '손에서 멀어짐'으로 본다.
    pinky_base = hand[PINKY_MCP]
    index_base = hand[INDEX_MCP]
    far_from_pinky = _dist(hand[THUMB_TIP], pinky_base) > _dist(hand[THUMB_IP], pinky_base) * THUMB_RATIO
    far_from_index = _dist(hand[THUMB_TIP], index_base) > _dist(hand[THUMB_IP], index_base) * THUMB_RATIO

    # 엄지 끝이 검지 뿌리에서 손바닥 크기 x THUMB_SPREAD_RATIO 보다 가까우면 손바닥에 붙은(접히거나 가려진) 엄지다.
    # 엄지가 손등 뒤로 숨으면 모델이 관절을 손 한가운데에 찍는데, 위의 거리비 조건만으로는 걸러지지 않았다.
    # 단, 엄지가 길게(뿌리~끝이 손바닥만큼) 곧게(IP 각도 160도 이상) 뻗어 있으면 손바닥 옆에 붙여서 편 엄지다.
    # (손을 활짝 펴고 엄지를 검지 쪽으로 붙인 자세. 접히거나 가려진 엄지는 짧거나 꺾여 있다.)
    # 손바닥 바깥의 편 엄지(visible_thumb)는 살짝 굽었거나 비스듬해 짧아 보여도(THUMB_REACH_MIN_SIDE) 펴진 엄지로 본다.
    straight_long = visible_thumb or (
        metrics["reach2d"] >= THUMB_REACH_MIN and thumb_angle >= THUMB_STRAIGHT_ANGLE)

    if spread_from_index < THUMB_SPREAD_RATIO and not straight_long:
        return False, "spread", metrics   # 엄지 끝이 검지 뿌리 근처에 붙어 있다 -> 굽힘

    # 엄지가 손바닥을 가로질러 약지·새끼 쪽에 붙은 경우(V 사인)는 검지 뿌리에서는 멀어 보여서 위 조건을 통과한다.
    # 그래서 손바닥 '중심'(손목 + 네 손가락 뿌리의 평균)에서도 재서, 가까우면 손바닥 위로 접힌 엄지로 본다.
    if near_center < THUMB_CENTER_RATIO and not straight_long:
        return False, "center", metrics   # 엄지 끝이 손바닥 위에 있다 -> 굽힘

    # 엄지 끝이 검지 끝 등에 닿아 있어도(OK 사인) 엄지 자체가 곧게 뻗었으면 펴진 것으로 센다.
    # (닿은 쪽 손가락을 굽힘으로 처리하는 건 is_finger_open 에서 한다.)
    if not (far_from_pinky or far_from_index) and not straight_long:
        return False, "near", metrics     # 엄지 끝이 관절보다 손에서 멀어지지 않았다
    # 3D 로 엄지가 검지 뿌리에서 멀리 뻗어 있으면(손바닥의 THUMB_WIDE_SPREAD_3D 배 이상) 마디가 조금 굽어 있어도 편 엄지다.
    # (힘을 뺀 편 손의 엄지는 화면 각도 139도까지 굽는다. 주먹 밖으로 휜 엄지는 3D 거리가 0.5 근처였다.)
    wide_in_3d = world is not None and metrics["spread3d"] >= THUMB_WIDE_SPREAD_3D
    # 꺾임 기준은 손 모양에 따라 다르다. 주먹(손가락 3개 이상 접힘)에서는 끝이 휜 엄지를 접힘으로 보지만(THUMB_ANGLE),
    # 손을 펴고 있을 때는 엄지가 힘이 빠져 138~140도로 굽어도 펴진 엄지다. 이때는 많이 꺾였을 때만(THUMB_ANGLE_OPEN_HAND) 접힘.
    # (엄지를 손바닥 쪽으로 접으면 위의 spread / center / 3D 규칙이 먼저 걸러낸다.)
    bend_limit = THUMB_ANGLE if fist else THUMB_ANGLE_OPEN_HAND
    metrics["fist"] = 1.0 if fist else 0.0
    # 엄지를 세워도 화면에서는 끝마디가 비스듬히 보여 각도가 140도대로 나온다. 3D 각도는 손을 돌려도 변하지 않아서,
    # 주먹일 때는 3D 각도도 THUMB_ANGLE_3D 이하일 때만 꺾인 엄지로 본다. (엄지척 3D 159~164, 주먹 밖으로 휜 엄지 141)
    if world is not None:
        metrics["ip3d"] = _angle(world[2], world[THUMB_IP], world[THUMB_TIP])
    bent_in_3d = world is None or not fist or metrics["ip3d"] <= THUMB_ANGLE_3D
    if thumb_angle <= bend_limit and not wide_in_3d and bent_in_3d:
        return False, "bent", metrics     # 엄지 마디가 많이 꺾여 있다
    return True, "open", metrics


def is_thumb_open(hand, world=None, depth=None, fist=True):
    """엄지가 펴졌으면 True, 굽혔으면 False. (판정 이유가 필요하면 diagnose_thumb)"""
    return diagnose_thumb(hand, world, depth, fist)[0]


def _angle(a, b, c):
    """점 b 에서 a-b-c 가 이루는 각도(도). 곧게 펴지면 180도에 가깝다. (x, y, z 3차원 계산)"""
    v1 = [a[k] - b[k] for k in range(3)]
    v2 = [c[k] - b[k] for k in range(3)]
    n1 = math.sqrt(sum(x * x for x in v1))
    n2 = math.sqrt(sum(x * x for x in v2))
    if n1 == 0 or n2 == 0:
        return 180.0
    cos = sum(x * y for x, y in zip(v1, v2)) / (n1 * n2)
    return math.degrees(math.acos(max(-1.0, min(1.0, cos))))


def _world_says_closed(world, mcp, pip, dip, tip):
    """실제 3D 좌표(world)로 본 접힘 판정. 손을 어느 방향으로 돌려도 길이·각도가 변하지 않아서 옆모습에 강하다.

    둘 중 하나라도 해당하면 접힘:
      1) 손끝~손목 거리가 (뿌리~손목 거리) x WORLD_EXT_MIN 보다 짧다 (펴면 1.5~2.3, 접으면 0.5~1.1)
      2) PIP 관절의 3D 각도가 WORLD_PIP_MIN 도 이하다 (펴면 140도 이상, 접으면 76~96도)
    """
    wrist = world[WRIST]
    extension = math.dist(world[tip], wrist) / (math.dist(world[mcp], wrist) or 1e-6)
    pip_angle = _angle(world[mcp], world[pip], world[dip])
    return extension < WORLD_EXT_MIN or pip_angle <= WORLD_PIP_MIN


def diagnose_finger(hand, mcp, tip, pip, dip, world=None, depth=None):
    """한 손가락을 판정하고 '왜 그렇게 나왔는지'도 같이 돌려준다. 반환: (펴짐 여부, 이유, 측정값 dict).

    이유: hidden(다른 손가락 뒤에 가려짐) / touch(엄지에 닿음) / 3D-ext(3D 거리비 짧음) / 3D-pip(3D PIP 각도 작음) /
          wrist(손끝이 PIP 보다 손목에 가까움) / 2D-pip(화면 PIP 각도 작음) / open(펴짐)
    측정값: pip2d(화면 PIP 각도), pip3d(3D PIP 각도), ext3d(3D 손끝~손목 / 뿌리~손목), wrist_ratio(손끝~손목 / PIP~손목)
    """
    pip_angle = _angle(hand[mcp], hand[pip], hand[dip])   # 손가락 뿌리-PIP-DIP 각도
    wrist_ratio = _dist(hand[WRIST], hand[tip]) / (_dist(hand[WRIST], hand[pip]) or 1e-6)
    bend2d = (180 - pip_angle) + (180 - _angle(hand[pip], hand[dip], hand[tip]))
    metrics = {"pip2d": pip_angle, "wrist_ratio": wrist_ratio, "bend2d": bend2d}
    if world is not None:
        metrics["pip3d"] = _angle(world[mcp], world[pip], world[dip])
        metrics["ext3d"] = math.dist(world[tip], world[WRIST]) / (math.dist(world[mcp], world[WRIST]) or 1e-6)
        metrics["bend3d"] = (180 - metrics["pip3d"]) + (180 - _angle(world[pip], world[dip], world[tip]))

    # 화면에서 손가락이 곧게 보이면(PIP 크고 굽힘 합계가 작으면) 3D 접힘 판정을 쓰지 않는다.
    # 손을 돌리면 MediaPipe 3D 값이 접힌 것처럼 줄어들어, 곧게 편 검지가 접힘으로 나왔다.
    # 옆모습에서 접힌 손가락은 화면 PIP 가 100~120도라 이 조건에 안 걸려 3D 판정이 그대로 작동한다.
    # 가려진 손가락은 모델이 점을 곧게 이어 펴짐처럼 만든다. 화면에서 겹치고 앞 관절이 더 가까우면 각도를 믿지 않는다.
    if _finger_hidden(hand, depth, mcp, pip, dip, tip):
        return False, "hidden", metrics
    looks_straight = pip_angle > WORLD_TRUST_2D_PIP and bend2d < WORLD_TRUST_2D_BEND
    # 엄지 끝에 닿은 손가락은 접힘으로 본다(OK 사인). 단, 곧게 뻗은 손가락은 제외한다.
    # 진짜 OK 사인은 닿은 손가락이 동그랗게 굽어 있다. 곧게 뻗은 새끼 위에 엄지 끝이 화면에서 겹쳐 보이기만 하면 닿은 게 아니다.
    if _touches_thumb(hand, tip) and not looks_straight:
        return False, "touch", metrics   # 엄지와 닿아 동그라미를 만들고 있다 (OK 사인) -> 굽힘
    if world is not None:
        # 가려진 손가락을 모델이 곧게 이으면 화면은 펴짐처럼 보여도 3D 길이는 접힌 손가락 수준이다.
        # 그 경우만 화면이 곧아도 3D 거리비를 쓴다. 진짜 편 손가락은 1.17 이상이라 해당 없다.
        if metrics["ext3d"] < WORLD_FAKE_STRAIGHT_EXT:
            return False, "3D-ext", metrics
        if not looks_straight:
            if metrics["ext3d"] < WORLD_EXT_MIN:
                return False, "3D-ext", metrics   # 3D 로 손끝이 손목에서 충분히 멀지 않다
            if metrics["pip3d"] <= WORLD_PIP_MIN:
                return False, "3D-pip", metrics   # 3D 로 PIP 관절이 많이 꺾여 있다
            if metrics["bend3d"] >= WORLD_TOTAL_BEND:
                return False, "3D-hook", metrics  # 3D 로 PIP + DIP 합계 굽힘이 크다
    if bend2d >= THRESHOLD_TOTAL_BEND:
        return False, "hook", metrics         # PIP + DIP 합계 굽힘이 크다 (갈고리 모양) -> 굽힘
    if wrist_ratio <= THRESHOLD_RATIO:
        return False, "wrist", metrics        # 손끝이 PIP 보다 손목에 가깝다 = 손바닥 쪽으로 말려 접혔다
    if pip_angle > THRESHOLD_ANGLE:
        return True, "open", metrics          # PIP 관절이 90도 미만으로 꺾이지 않았다 -> 펴짐
    return False, "2D-pip", metrics           # PIP 관절이 90도 이상 꺾였다 -> 굽힘


def is_finger_open(hand, mcp, tip, pip, dip, world=None, depth=None):
    """검지~새끼 중 한 손가락이 펴졌으면 True, 굽혔으면 False. (판정 이유가 필요하면 diagnose_finger)

    기준은 단순하게: PIP 관절이 90도 이상 꺾여야(관절 각도가 THRESHOLD_ANGLE 이하) '접힘', 그보다 덜 꺾이면 '펴짐'.
    (애매하게 살짝 굽은 손가락은 펴진 것으로 센다. 손끝이 손목 쪽으로 말린 경우와 엄지에 닿은 경우는 따로 거른다.)
    world(실제 3D 좌표)를 주면, 화면(2D)에서는 곧게 보여도 3D 로 접혀 있는 손가락(옆모습)을 추가로 접힘 처리한다.
    """
    return diagnose_finger(hand, mcp, tip, pip, dip, world, depth)[0]


class FingerStabilizer:
    """영상/웹캠용: 손가락별 상태가 여러 프레임 연속 우세해야 바뀌게 해서, 좌표 떨림으로 숫자가 깜빡이는 걸 막는다.

    사진은 한 장이라 떨림이 없지만, 웹캠은 손이 계속 미세하게 움직이고 화질이 낮아서 프레임마다 관절 좌표가 떨린다.
    손가락 상태가 기준선 근처에 있으면 프레임마다 펴짐/접힘이 뒤집히므로,
    최근 window 프레임 중 반대 상태가 need 번 이상 나와야 비로소 상태를 바꾼다.
    (window=7, need=4 이면 자세를 바꾼 뒤 약 2프레임(30fps 에서 0.07초) 만에 따라가고, 그보다 짧은 뒤집힘은 무시한다.
     window=9, need=6 으로 올리면 더 안정적이지만 반응이 3~4프레임 느려진다.)
    """

    def __init__(self, window=7, need=4):
        self.window = window
        self.need = need
        self.history = {}   # (손 번호, 손가락 이름) -> 최근 상태들
        self.stable = {}    # (손 번호, 손가락 이름) -> 지금 인정하는 상태

    def reset(self):
        """손이 사라졌을 때 호출. 다음에 손이 나타나면 처음부터 다시 시작한다."""
        self.history.clear()
        self.stable.clear()

    def update(self, hand_index, state):
        """한 프레임의 손가락 상태({이름: True/False})를 넣으면 안정화된 상태를 돌려준다."""
        result = {}
        for name, is_open in state.items():
            key = (hand_index, name)
            recent = self.history.setdefault(key, deque(maxlen=self.window))
            recent.append(is_open)
            current = self.stable.get(key, is_open)         # 처음 본 값은 그대로 인정
            if sum(1 for v in recent if v != current) >= self.need:
                current = not current                       # 반대 상태가 충분히 쌓였을 때만 바꾼다
            self.stable[key] = current
            result[name] = current
        return result


def _thumb_over_curled_fingers(hand, state):
    """엄지 끝이 접힌 손가락들 위에 포개져 있으면 True (V 사인에서 엄지를 손바닥 위로 접은 모양).

    이 자세에서는 엄지 끝이 접힌 손가락 끝과 겹쳐서 OK 사인(엄지 끝이 다른 손끝에 닿음)과 똑같이 보이고,
    그러면 엄지가 '곧게 뻗은' 것으로 세어진다. 둘의 차이는 엄지가 손에서 얼마나 멀리 있느냐다.
    OK 사인은 엄지가 손바닥 중심에서 멀리 뻗어 있고, 포갠 엄지는 손바닥 위(중심 가까이)에 있다.
    """
    palm = _palm_size(hand)
    ids = (WRIST, INDEX_MCP, MIDDLE_MCP, 13, PINKY_MCP)
    cx = sum(hand[i][0] for i in ids) / 5
    cy = sum(hand[i][1] for i in ids) / 5
    center = math.hypot(hand[THUMB_TIP][0] - cx, hand[THUMB_TIP][1] - cy) / palm
    # 손가락 세 개 이상이 접힌 주먹이면 엄지를 주먹 옆에 붙인 자세도 포개진 것으로 본다. 이때는 엄지가 손바닥 중심에서
    # 멀어 보여도(손목을 기울이면 1.0~1.4배) 엄지 끝이 접힌 손가락 관절에 더 가까이(THUMB_FIST_HUG_DIST) 붙어 있으면 접힘이다.
    # OK 사인은 접힌 손가락이 한두 개뿐이라 이 예외에 걸리지 않는다.
    fist = sum(1 for name in FINGERS if not state[name]) >= 3
    if center > THUMB_FOLD_CENTER and not fist:
        return False   # 엄지가 손에서 멀리 있다 -> 포갠 것이 아니다
    limit = THUMB_FIST_HUG_DIST if fist else THUMB_FOLD_DIST
    for name, (_mcp, pip, dip, tip) in FINGERS.items():
        if state[name]:
            continue   # 펴진 손가락 위에 엄지가 있는 것은 상관없다
        for j in (pip, dip, tip):
            if _dist(hand[THUMB_TIP], hand[j]) / palm < limit:
                return True
    return False


def count_fingers(hand, world=None, depth=None):
    """한 손(21개 좌표)의 펼친 손가락 수와 손가락별 상태를 돌려준다.

    world: 실제 3D 좌표(선택). 주면 손가락 판정에 3D 조건을 더한다.
    반환: (개수, {"thumb": True/False, "index": ..., ...})
    """
    state = {}
    for name, (mcp, pip, dip, tip) in FINGERS.items():
        state[name] = is_finger_open(hand, mcp, tip, pip, dip, world, depth)
    # 엄지 꺾임 기준은 주먹(다른 손가락 3개 이상 접힘)인지에 따라 다르다. 그래서 엄지를 마지막에 판정한다.
    fist = sum(1 for v in state.values() if not v) >= 3
    state = {"thumb": is_thumb_open(hand, world, depth, fist), **state}

    if state["thumb"] and _thumb_over_curled_fingers(hand, state):
        state["thumb"] = False   # 접힌 손가락 위에 포개진 엄지 (V 사인에서 엄지를 접은 모양)

    count = sum(state.values())   # True 는 1, False 는 0 으로 더해진다
    return count, state
